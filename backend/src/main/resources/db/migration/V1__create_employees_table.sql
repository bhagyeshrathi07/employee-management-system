CREATE TABLE employees (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     VARCHAR(20)    NOT NULL,
    full_name       VARCHAR(100)   NOT NULL,
    email           VARCHAR(150)   NOT NULL,
    phone_number    VARCHAR(20)    NOT NULL,
    department      VARCHAR(30)    NOT NULL,
    designation     VARCHAR(100)   NOT NULL,
    date_of_joining DATE           NOT NULL,
    salary          NUMERIC(12, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    created_at      TIMESTAMP(6)   NOT NULL,
    updated_at      TIMESTAMP(6)   NOT NULL,

    CONSTRAINT uk_employee_employee_id UNIQUE (employee_id),
    CONSTRAINT uk_employee_email       UNIQUE (email),
    CONSTRAINT employees_department_check CHECK (department IN
        ('ENGINEERING', 'PRODUCT', 'DESIGN', 'MARKETING', 'SALES', 'HR', 'FINANCE', 'OPERATIONS')),
    CONSTRAINT employees_status_check CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_employee_department ON employees (department);
CREATE INDEX idx_employee_status     ON employees (status);
CREATE INDEX idx_employee_full_name  ON employees (full_name);

COMMENT ON TABLE  employees                 IS 'Employee master records managed by the Employee Management System';
COMMENT ON COLUMN employees.employee_id     IS 'Business identifier, e.g. EMP-1001 (unique)';
COMMENT ON COLUMN employees.email           IS 'Work email address (unique, stored lower-case)';
COMMENT ON COLUMN employees.department      IS 'One of ENGINEERING, PRODUCT, DESIGN, MARKETING, SALES, HR, FINANCE, OPERATIONS';
COMMENT ON COLUMN employees.salary          IS 'Annual salary, 2 decimal places';
COMMENT ON COLUMN employees.status          IS 'ACTIVE or INACTIVE';
